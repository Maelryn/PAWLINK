// src/adapter.mjs
// Converts the AI's internal v0.2 result → the backend's AIAnalysis shape.
//
// The backend type (apps/backend/src/shared/types.ts) expects:
//   triage, confidence (number), summary, observedSigns, safetyAdvice,
//   possiblyContagious, contagionAdvice?, recommendedHelp, suggestedServices,
//   suggestedHelpers?, forcedUrgentByRule, disclaimer, model
//
// The AI's internal format uses different names and enum values.
// This file is the bridge.  The backend fills suggestedServices and
// suggestedHelpers using PostGIS — we always return empty arrays for those.

import { readFileSync } from "node:fs";

// ── Guidance library (for expanding keys → human-readable safetyAdvice text) ─
const libraryPath = new URL("../data/guidance_library.json", import.meta.url);
const library = JSON.parse(readFileSync(libraryPath, "utf8"));
const guidanceMap = Object.fromEntries(library.keys.map((k) => [k.key, k.text_en]));

// ── Legal disclaimer (required by the backend contract) ──────────────────────
const DISCLAIMER =
  "This analysis is generated by an AI model and is not a veterinary diagnosis. " +
  "Always consult a licensed veterinarian for medical advice. " +
  "In an emergency, contact a vet immediately.";

// ── Enum mappings ─────────────────────────────────────────────────────────────

/**
 * AI urgency  →  backend Triage
 *   urgent          → urgent
 *   needs_attention → monitoring
 *   non_urgent      → stable
 */
const URGENCY_TO_TRIAGE = {
  urgent: "urgent",
  needs_attention: "monitoring",
  non_urgent: "stable",
};

/**
 * AI confidence string → numeric confidence (0–1)
 *   high   → 0.9
 *   medium → 0.6
 *   low    → 0.3
 */
const CONFIDENCE_TO_NUMBER = {
  high: 0.9,
  medium: 0.6,
  low: 0.3,
};

/**
 * AI `needs` values → backend HelpType values
 *   veterinarian      → medical
 *   rescue_volunteer  → search
 *   transport         → transport
 *   shelter           → boarding
 *   foster            → foster
 *   specialized_rescue→ search   (closest match; backend dispatches the right team)
 */
const NEEDS_TO_HELP_TYPE = {
  veterinarian: "medical",
  rescue_volunteer: "search",
  transport: "transport",
  shelter: "boarding",
  foster: "foster",
  specialized_rescue: "search",
};

// ── Helpers ───────────────────────────────────────────────────────────────────

/** Build the `observedSigns` array from the AI result's structured fields. */
function buildObservedSigns(result) {
  const signs = [];

  if (result.situation_category && result.situation_category !== "unclear") {
    signs.push(result.situation_category.replace(/_/g, " "));
  }

  for (const flag of result.red_flags ?? []) {
    const readable = flag.replace(/_/g, " ");
    if (!signs.includes(readable)) signs.push(readable);
  }

  for (const hazard of result.hazards ?? []) {
    const readable = `hazard: ${hazard.replace(/_/g, " ")}`;
    if (!signs.includes(readable)) signs.push(readable);
  }

  return signs;
}

/** Expand guidance keys → readable safety advice strings. */
function buildSafetyAdvice(guidanceKeys) {
  return (guidanceKeys ?? [])
    .map((key) => guidanceMap[key])
    .filter(Boolean);
}

/** Map AI needs[] → HelpType[], deduplicated. */
function buildRecommendedHelp(needs) {
  const seen = new Set();
  const result = [];
  for (const need of needs ?? []) {
    const mapped = NEEDS_TO_HELP_TYPE[need];
    if (mapped && !seen.has(mapped)) {
      seen.add(mapped);
      result.push(mapped);
    }
  }
  return result;
}

// ── Main converter ────────────────────────────────────────────────────────────

/**
 * Convert an AI triage result (v0.2 internal format) into the
 * AIAnalysis shape expected by the PawLink backend.
 *
 * @param {{ result, model, ms, usage, ai_status }} triageOutput
 *   — the return value of triage() from src/triage.mjs
 * @returns {import('../../backend/src/shared/types').AIAnalysis}
 */
export function toAIAnalysis(triageOutput) {
  const { result, model } = triageOutput;

  const triage = URGENCY_TO_TRIAGE[result.urgency] ?? "monitoring";
  const confidence = CONFIDENCE_TO_NUMBER[result.confidence] ?? 0.3;

  const possiblyContagious =
    (result.hazards ?? []).includes("contagion_risk") ||
    (result.red_flags ?? []).includes("suspected_contagious_serious");

  const contagionAdvice = possiblyContagious
    ? [
        guidanceMap["separate_from_other_animals"],
        guidanceMap["dont_mix_with_other_animals"],
      ].filter(Boolean)
    : undefined;

  return {
    triage,
    confidence,
    summary: result.summary ?? "No summary available.",
    observedSigns: buildObservedSigns(result),
    safetyAdvice: buildSafetyAdvice(result.guidance_keys),
    possiblyContagious,
    ...(contagionAdvice ? { contagionAdvice } : {}),
    recommendedHelp: buildRecommendedHelp(result.needs),
    suggestedServices: [],   // filled by backend (PostGIS)
    // suggestedHelpers: []  // omitted; filled by backend
    forcedUrgentByRule: result.forced_urgent_by_rule ?? result.forcedUrgentByRule ?? false,
    disclaimer: DISCLAIMER,
    model: model ?? process.env.GEMINI_MODEL ?? "unknown",
  };
}

/**
 * Full pipeline helper: run triage + convert to AIAnalysis in one call.
 * Convenience for the NestJS route that calls the AI module.
 *
 * @param {string} reportText
 * @param {Function} triageFn   — injectable for testing (default: triage)
 * @returns {{ aiAnalysis, raw, ms, ai_status }}
 */
export async function analyseReport(reportText, triageFn) {
  // Lazy-import triage to avoid circular dependencies in tests
  if (!triageFn) {
    const { triage } = await import("./triage.mjs");
    triageFn = triage;
  }

  const triageOutput = await triageFn(reportText);
  const aiAnalysis = toAIAnalysis(triageOutput);

  return {
    aiAnalysis,
    raw: triageOutput.result,     // the full v0.2 internal result (store as JSONB)
    ms: triageOutput.ms,
    ai_status: triageOutput.ai_status,
  };
}

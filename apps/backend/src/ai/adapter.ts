// Enum mappings

/**
 * AI urgency  →  backend Triage
 *   urgent          → urgent
 *   needs_attention → monitoring
 *   non_urgent      → stable
 *   stable          → stable
 */
const URGENCY_TO_TRIAGE: Record<string, 'urgent' | 'monitoring' | 'stable'> = {
  urgent: 'urgent',
  needs_attention: 'monitoring',
  non_urgent: 'stable',
  stable: 'stable',
};

/**
 * AI confidence string → numeric confidence (0–1)
 *   high   → 0.9
 *   medium → 0.6
 *   low    → 0.3
 */
const CONFIDENCE_TO_NUMBER: Record<string, number> = {
  high: 0.9,
  medium: 0.6,
  low: 0.3,
};

/**
 * AI `needs` values → backend HelpType values
 *   veterinarian      → medical
 *   rescue_volunteer  → search
 *   transport         → transport
 *   shelter           → boarding
 *   foster            → foster
 *   specialized_rescue→ search   (closest match; backend dispatches the right team)
 */
const NEEDS_TO_HELP_TYPE: Record<string, HelpType> = {
  veterinarian: 'medical',
  rescue_volunteer: 'search',
  transport: 'transport',
  shelter: 'boarding',
  foster: 'foster',
  specialized_rescue: 'search',
};

// Helpers

/** Build the `observedSigns` array from the AI result's structured fields. */
function buildObservedSigns(result: AIRaw): string[] {
  const signs: string[] = [];

  if (result.situation_category && result.situation_category !== 'unclear') {
    signs.push(result.situation_category.replace(/_/g, ' '));
  }

  for (const flag of result.red_flags ?? []) {
    const readable = flag.replace(/_/g, ' ');
    if (!signs.includes(readable)) signs.push(readable);
  }

  for (const hazard of result.hazards ?? []) {
    const readable = `hazard: ${hazard.replace(/_/g, ' ')}`;
    if (!signs.includes(readable)) signs.push(readable);
  }

  return signs;
}

/** Map AI needs[] → HelpType[], deduplicated. */
function buildRecommendedHelp(needs: string[]): HelpType[] {
  const seen = new Set<HelpType>();
  const result: HelpType[] = [];
  for (const need of needs ?? []) {
    const mapped = NEEDS_TO_HELP_TYPE[need];
    if (mapped && !seen.has(mapped)) {
      seen.add(mapped);
      result.push(mapped);
    }
  }
  return result;
}

/**
 * Convert an AI triage result (v0.2 internal format) into the
 * AIAnalysis shape expected by the PawLink backend.
 */
export function toAIAnalysis(raw: AIRaw, model: string, lang: 'fr' | 'en' | 'ar'): AIAnalysis {
  const triage = URGENCY_TO_TRIAGE[raw.urgency] ?? 'monitoring';
  const confidence = typeof raw.confidence === 'number'
    ? raw.confidence
    : (CONFIDENCE_TO_NUMBER[raw.confidence] ?? 0.3);

  const possiblyContagious =
    (raw.hazards ?? []).includes('contagion_risk') ||
    (raw.red_flags ?? []).includes('suspected_contagious_serious');

  const contagionAdvice = possiblyContagious
    ? [
        'Separate from other animals',
        'Do not mix with other animals',
      ]
    : undefined;

  const disclaimer = DISCLAIMERS[lang] || DISCLAIMERS.en;

  const analysis: AIAnalysis = {
    triage,
    confidence,
    summary: raw.summary ?? 'No summary available.',
    observedSigns: buildObservedSigns(raw),
    safetyAdvice: raw.guidance_keys ?? [], // Would be expanded from guidance library in full implementation
    possiblyContagious,
    ...(contagionAdvice ? { contagionAdvice } : {}),
    recommendedHelp: buildRecommendedHelp(raw.needs),
    suggestedServices: [], // filled by backend (PostGIS)
    suggestedHelpers: [], // filled by backend
    forcedUrgentByRule: Boolean(raw.forced_urgent_by_rule ?? raw.forcedUrgentByRule ?? false),
    disclaimer,
    model: model ?? process.env.GEMINI_MODEL ?? 'unknown',
  };

  // Add photo verification outputs if available
  if (raw.animalDetected !== undefined) {
    analysis.animalDetected = Boolean(raw.animalDetected);
  }
  if (raw.isRealPhoto !== undefined) {
    analysis.isRealPhoto = Boolean(raw.isRealPhoto);
  }
  if (raw.speciesDetected) {
    analysis.speciesDetected = raw.speciesDetected as Species;
  }

  return analysis;
}
